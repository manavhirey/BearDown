#!/usr/bin/env python3
"""CoachBear dashboard server.

Dependency-free (Python 3.12 stdlib) local web app that:
  - stores and serves weekly training plans generated by the `coach-bear`
    Claude Code subagent (plans/<YYYY-Www>.md + .json sidecar metadata)
  - invokes the subagent headlessly (`claude --agent coach-bear -p ...`)
    to generate a week's plan or answer follow-up chat, as background jobs
  - parses the agent's strict plan format into structured day cards
  - stores workout logs (lifting sets, cardio sessions) and a mirror of past
    plans in SQLite (data/coachbear.db, see dashboard/db.py) and serves them
    as a training-log API with add/delete endpoints

Run:  python3 dashboard/server.py [--port 8737]
Env:  COACH_MOCK=1          use a canned plan instead of calling claude (testing)
      COACH_CLAUDE_BIN      path to the claude CLI (default: "claude")
      COACH_GEN_TIMEOUT     plan-generation timeout in seconds (default 1800)
      COACH_CHAT_TIMEOUT    chat timeout in seconds (default 900)
"""

